// Regenerates src/web/lib/brand-icons.ts from simple-icons (CC0), keeping only the SVG path and color,
// so no metadata (source/license URLs) ends up in the bundle. Usage: node scripts/gen-brand-icons.cjs
const { writeFileSync, readFileSync } = require('node:fs');
const { join } = require('node:path');
const si = require('simple-icons');

const wanted = JSON.parse(readFileSync(join(__dirname, 'brand-icons.json'), 'utf8'));
const lines = Object.entries(wanted).map(([name, key]) => {
  const icon = si[key];
  if (!icon) throw new Error(`simple-icons has no ${key} (${name})`);
  return `  ${JSON.stringify(name)}: { hex: ${JSON.stringify(icon.hex)}, path: ${JSON.stringify(icon.path)} },`;
});
writeFileSync(
  join(__dirname, '..', 'src', 'web', 'lib', 'brand-icons.ts'),
  `// Generated by scripts/gen-brand-icons.cjs from simple-icons (CC0). Do not edit by hand.\n\nexport interface BrandIcon {\n  path: string;\n  hex: string;\n}\n\nexport const BRAND_ICONS: Record<string, BrandIcon> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`${lines.length} icons`);
